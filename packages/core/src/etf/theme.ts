/**
 * 热点主题判定。`category` 是兜底（没匹配到方向时分类本身就是主题）。
 */
export function classifyEtfTheme(
  name: string,
  indexName: string | null,
  category: EtfCategory,
): string {
  const text = indexName === null || indexName === '' ? name : `${name} ${indexName}`;
  for (const [label, pattern] of RULES) {
    if (pattern.test(text)) return label;
  }
  return category;
}

export interface ThemeCoverage {
  total: number;
  /** 命中规则表（非兜底）的只数 */
  matched: number;
  /** 落入兜底（= 分类）的只数 */
  fallback: number;
  /** 兜底占比（回归护栏：上升说明规则表跟不上新品种） */
  fallbackRatio: number;
  themes: Map<string, number>;
}

/**
 * 分类覆盖统计。用 1675 只真实名单跑（`theme.test.ts`），
 * 兜底比例显著上升 = 规则表失效，是「规则是否还跟得上市场」的回归护栏。
 */
export function themeCoverage(
  rows: readonly { name: string; indexName: string | null; category: EtfCategory }[],
): ThemeCoverage {
  const themes = new Map<string, number>();
  let fallback = 0;
  for (const row of rows) {
    const theme = classifyEtfTheme(row.name, row.indexName, row.category);
    themes.set(theme, (themes.get(theme) ?? 0) + 1);
    if (theme === row.category) fallback += 1;
  }
  const total = rows.length;
  return {
    total,
    matched: total - fallback,
    fallback,
    fallbackRatio: total === 0 ? 0 : fallback / total,
    themes,
  };
}
